package Resposta10;

public class Calculadora {

    double soma;
    double subtrair;
    double multiplicar;
    double dividir;

    double somar(double a, double b){
        return a + b;
    }

    double subtrair(double a, double b){
        return a - b;
    }

    double multiplicar(double a, double b){
        return a * b;
    }

    double dividir(double a, double b) {
        return a / b;
    }
}
