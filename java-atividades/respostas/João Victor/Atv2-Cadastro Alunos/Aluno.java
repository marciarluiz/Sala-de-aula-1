public class Aluno {

    // Atributos
    String nome;
    int idade;
    String curso;
    int matricula;

    // Método para exibir os dados
    public void exibirDados() {
        System.out.println("Nome: " + nome);
        System.out.println("Idade: " + idade);
        System.out.println("Curso: " + curso);
        System.out.println("Matrícula: " + matricula);
        System.out.println("-------------------------");
    }
}
